test('backend outage is explicit and can be retried', async ({ page, request }) => {
  await login(page)
  try {
    await request.post('http://127.0.0.1:4302/test/failure/on')
    await page.getByRole('button', { name: 'Next', exact: true }).click()
    await expect(page.getByRole('alert')).toContainText('Contribution service is unavailable')
  } finally {
    await request.post('http://127.0.0.1:4302/test/failure/off')
  }
  await page.getByRole('button', { name: 'Retry' }).click()
  await expect(page.getByRole('link', { name: 'Sam Chen' })).toBeVisible()
})

