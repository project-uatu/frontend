test('project charts rank only the visible page and refresh on pagination', async ({ page }) => {
  await page.route('**/api/persons/*/projects?*', async route => {
    const next = new URL(route.request().url()).searchParams.has('cursor')
    await route.fulfill({ json: next
      ? { data: [{ project: 'next/project', count: 7 }], page: { has_more: false } }
      : { data: [{ project: 'first/project', count: 2 }, { project: 'busy/project', count: 10 }],
        page: { has_more: true, next_cursor: 'next' } },
    })
  })
  await login(page)
  await page.getByRole('link', { name: 'Alex Rivera' }).click()
  const projects = page.locator('section').filter({ has: page.getByRole('heading', { name: 'Contributed projects', exact: true }) })
  await expect(projects.getByRole('heading', { name: 'Most active projects on this page' })).toBeVisible()
  await expect(projects.locator('canvas')).toBeVisible()
  await expect(projects.getByRole('cell', { name: 'busy/project' })).toBeVisible()
  await projects.getByRole('button', { name: 'Next', exact: true }).click()
  await expect(projects.getByRole('cell', { name: 'next/project' })).toBeVisible()
  await expect(projects.getByRole('cell', { name: 'busy/project' })).toHaveCount(0)
  await expect(projects.getByRole('heading', { name: 'Most active projects on this page' })).toBeVisible()
  await expect(projects.locator('canvas')).toBeVisible()
})

test('profile sections have independent all-history defaults, presets, date ranges and pagination', async ({ page }) => {
  const requests: URL[] = []
  const activityRequests: URL[] = []
  const historyRequests: URL[] = []
  page.on('request', request => {
    const url = new URL(request.url())
    if (url.pathname.endsWith('/activity')) activityRequests.push(url)
    if (url.pathname.endsWith('/counts')) historyRequests.push(url)
  })
  await page.route('**/api/persons/*/projects?*', async route => {
    const url = new URL(route.request().url())
    requests.push(url)
    const ranged = url.searchParams.has('from')
    const next = url.searchParams.has('cursor')
    await route.fulfill({ json: {
      data: [{ project: ranged ? 'recent/project' : next ? 'older/project' : 'historic/project', count: 2 }],
      page: !ranged && !next ? { has_more: true, next_cursor: 'older' } : { has_more: false },
    } })
  })
  await login(page)
  await page.getByRole('link', { name: 'Alex Rivera' }).click()
  const projects = page.locator('section').filter({ has: page.getByRole('heading', { name: 'Contributed projects', exact: true }) })
  const history = page.locator('#contribution-history')
  const activity = page.locator('#recorded-activity')
  await expect(page.getByLabel('History period', { exact: true })).toHaveValue('year')
  await expect(page.getByLabel('Activity history', { exact: true })).toHaveValue('all')
  await expect(page.getByLabel('Activity type', { exact: true })).toHaveValue('')
  await expect(activity.getByText('Recorded commit abc123', { exact: true })).toBeVisible()
  expect(activityRequests[0].searchParams.has('from')).toBe(false)
  expect(activityRequests[0].searchParams.has('kind')).toBe(false)
  const initialHistory = historyRequests[0]
  const duration = Date.parse(initialHistory.searchParams.get('to')!) - Date.parse(initialHistory.searchParams.get('from')!)
  expect(duration / 86400000).toBeGreaterThanOrEqual(365)
  expect(duration / 86400000).toBeLessThanOrEqual(366)
  await expect(projects.getByRole('cell', { name: 'historic/project' })).toBeVisible()
  expect(requests[0].searchParams.has('from')).toBe(false)
  expect(requests[0].searchParams.has('to')).toBe(false)
  await projects.getByRole('button', { name: 'Next', exact: true }).click()
  await expect(projects.getByRole('cell', { name: 'older/project' })).toBeVisible()
  await activity.getByRole('button', { name: 'Next', exact: true }).click()
  await expect(activity.getByText('Earlier recorded commit', { exact: true })).toBeVisible()
  const projectRequestCount = requests.length
  const activityRequestCount = activityRequests.length
  await page.getByLabel('History period', { exact: true }).selectOption('ytd')
  await expect.poll(() => historyRequests.at(-1)?.searchParams.get('from')).toContain('-01-01T')
  await expect(projects.getByRole('cell', { name: 'older/project' })).toBeVisible()
  await expect(activity.getByText('Earlier recorded commit', { exact: true })).toBeVisible()
  expect(requests).toHaveLength(projectRequestCount)
  expect(activityRequests).toHaveLength(activityRequestCount)
  await page.getByLabel('History period', { exact: true }).selectOption('range')
  await history.getByLabel('From (UTC)', { exact: true }).fill('2026-01-01')
  await history.getByLabel('Through (UTC, inclusive)', { exact: true }).fill('2026-01-31')
  await history.getByRole('button', { name: 'Apply dates' }).click()
  await expect.poll(() => historyRequests.at(-1)?.searchParams.get('to')).toBe('2026-02-01T00:00:00.000Z')
  await page.getByLabel('Project history', { exact: true }).selectOption('range')
  await projects.getByRole('button', { name: 'Apply dates' }).click()
  await expect(projects.getByRole('cell', { name: 'recent/project' })).toBeVisible()
  expect(requests.at(-1)?.searchParams.has('from')).toBe(true)
  expect(requests.at(-1)?.searchParams.has('to')).toBe(true)
  expect(requests.at(-1)?.searchParams.has('cursor')).toBe(false)
  await expect(projects.getByRole('button', { name: 'Previous', exact: true })).toBeDisabled()
  await page.getByLabel('Project history', { exact: true }).selectOption('all')
  await expect(projects.getByRole('cell', { name: 'historic/project' })).toBeVisible()
  await page.getByLabel('Activity history', { exact: true }).selectOption('range')
  await activity.getByRole('button', { name: 'Apply dates' }).click()
  await expect(activity.getByText('Recorded commit abc123', { exact: true })).toBeVisible()
  expect(activityRequests.at(-1)?.searchParams.has('from')).toBe(true)
  expect(activityRequests.at(-1)?.searchParams.has('cursor')).toBe(false)
  await page.getByLabel('Activity type', { exact: true }).selectOption('commit_authored')
  await expect.poll(() => activityRequests.at(-1)?.searchParams.get('kind')).toBe('commit_authored')
  await page.getByLabel('Activity history', { exact: true }).selectOption('all')
  await expect.poll(() => activityRequests.at(-1)?.searchParams.has('from')).toBe(false)
  expect(historyRequests.at(-1)?.searchParams.get('to')).toBe('2026-02-01T00:00:00.000Z')
})

